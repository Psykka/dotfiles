#!/bin/sh
# Installs the login screen: greetd + tuigreet in a bare sway (user menu, session
# picker, password). The files go to /etc/greetd and /usr/local/bin
# (outside ~, so stow doesn't handle them) and greetd is enabled for the
# next boot.
#
# Usage: greeter/install-greeter.sh      (asks for the password)
set -eu

here=$(cd "$(dirname "$0")" && pwd)
SUDO=${SUDO:-sudo}

# The greeter's terminal in the theme's colors, for the 16 named colors
# tuigreet uses: black is the background, gray the text, darkgray the
# borders, white the highlights. No window decorations: sway draws none, so
# alacritty would draw its own title bar off the top of the screen and leave
# a black strip of that height at the bottom
stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT
python3 -I - "$stage/alacritty.toml" <<'PY'
import os, subprocess, sys
get = lambda k: subprocess.run([os.path.expanduser("~/.local/bin/theme"), "get", k],
                               capture_output=True, text=True).stdout.strip()
names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
normal = ["bg0", "red", "green", "yellow", "blue", "magenta", "cyan", "fg"]
bright = ["mute", "bright_red", "bright_green", "bright_yellow", "bright_blue", "bright_magenta", "bright_cyan", "hi"]
lines = ["# Generated by install-greeter.sh from the theme; the login screen's terminal",
         # no live reload: watching /etc/greetd is denied to the greeter (SELinux)
         "[general]", "live_config_reload = false", "",
         "[window]", "decorations = \"None\"", "dynamic_padding = true", "",
         "[font]", 'normal = { family = "JetBrains Mono" }', "size = 13", "",
         "[colors.primary]", f'background = "#{get("bg0")}"', f'foreground = "#{get("fg")}"']
for section, keys in (("normal", normal), ("bright", bright)):
    lines += ["", f"[colors.{section}]"] + [f'{n} = "#{get(k)}"' for n, k in zip(names, keys)]
with open(sys.argv[1], "w") as f:
    f.write("\n".join(lines) + "\n")
PY

# The main display (menu's Displays page), where the login screen shows:
# displays.py keeps this copy up to date, so it is ours to write
sed -n 's/^workspace 1 output "\(.*\)"$/\1/p' ~/.local/state/sway-displays.conf \
    2>/dev/null >"$stage/main-display" || true

$SUDO sh -c "
    set -e
    install -d /etc/greetd
    install -m 644 '$here/config.toml' '$stage/alacritty.toml' /etc/greetd/
    install -m 644 -o '$(id -un)' '$stage/main-display' /etc/greetd/
    install -m 755 '$here/login-session' '$here/login-screen' /usr/local/bin/
    # The console palette the greeter used before it ran in a compositor
    rm -f /etc/greetd/vtrgb
    # tuigreet remembers the last user and sessions here
    install -d -o greetd -g greetd /var/cache/tuigreet
    # With SELinux (Fedora) the greeter runs as xdm_t, which may not write
    # the plain var_t this folder gets, so nothing was ever remembered;
    # label it like the other display managers' state (/var/lib/greetd)
    if command -v semanage >/dev/null && selinuxenabled 2>/dev/null; then
        semanage fcontext -a -t xdm_var_lib_t '/var/cache/tuigreet(/.*)?' >/dev/null 2>&1 ||
            semanage fcontext -m -t xdm_var_lib_t '/var/cache/tuigreet(/.*)?'
        restorecon -R /var/cache/tuigreet
        # and give it a pty for the terminal it runs in (greeter-pty.cil)
        semodule -i '$here/greeter-pty.cil'
    fi

    # Unlocks the login keyring with the password typed at login, so apps
    # (VSCode, Firefox, nm-applet) never ask for it. Fedora's greetd already
    # does this; Arch's and Debian's don't. Fedora ships it in /usr/lib/pam.d
    # and a file in /etc/pam.d replaces that one whole, so never create
    # /etc/pam.d/greetd from nothing: with only these lines no module checks
    # the password and every login is refused.
    pam=/etc/pam.d/greetd
    [ -f \$pam ] || pam=/usr/lib/pam.d/greetd
    if [ -f \$pam ] && ! grep -q pam_gnome_keyring.so \$pam; then
        [ \$pam = /etc/pam.d/greetd ] || cp \$pam /etc/pam.d/greetd
        printf '%s\n' '-auth       optional    pam_gnome_keyring.so' \
            '-session    optional    pam_gnome_keyring.so auto_start' >> /etc/pam.d/greetd
    fi

    # The login screen is whatever owns the display-manager.service alias,
    # and that is all greetd has in its [Install]. With another greeter
    # (gdm, sddm, lightdm) holding the alias, a plain 'systemctl enable
    # greetd' fails and the old one keeps the screen, so turn it off first
    # and then take the alias over.
    old=\$(readlink -f /etc/systemd/system/display-manager.service 2>/dev/null || true)
    case \${old##*/} in
        ''|greetd.service) ;;
        *) echo \"Replacing \${old##*/} as the login screen\"
           systemctl disable \"\${old##*/}\" ;;
    esac
    systemctl enable --force greetd
    systemctl set-default graphical.target
"
echo "Login screen installed; it shows up at the next boot."
